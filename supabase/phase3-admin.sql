create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  action text not null check (length(action) <= 80),
  entity_type text not null default 'application' check (length(entity_type) <= 80),
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_audit_logs_created_at_idx on public.admin_audit_logs (created_at desc);
alter table public.admin_audit_logs enable row level security;
-- Intentionally no public policies. Read/write through the server-only service role only.
